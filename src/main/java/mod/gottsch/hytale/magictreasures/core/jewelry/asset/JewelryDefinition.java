package mod.gottsch.hytale.magictreasures.core.jewelry.asset;

import com.hypixel.hytale.assetstore.AssetExtraInfo;
import com.hypixel.hytale.assetstore.AssetRegistry;
import com.hypixel.hytale.assetstore.AssetStore;
import com.hypixel.hytale.assetstore.codec.AssetBuilderCodec;
import com.hypixel.hytale.assetstore.map.DefaultAssetMap;
import com.hypixel.hytale.assetstore.map.JsonAssetWithMap;
import com.hypixel.hytale.codec.Codec;
import com.hypixel.hytale.codec.KeyedCodec;

import javax.annotation.Nullable;

/**
 * What a jewelry item is: a Magic Treasures JSON asset under
 * {@code Server/MagicTreasures/Jewelry/}, with the same id as the item asset it describes
 * (for example {@code MT_Ring_Gold_Ruby_Great}). It names the type, material, style and
 * gem. Item assets can't carry extra fields, so this is how the plugin knows that an item
 * is jewelry. Both files are generated by {@code tools/generate_jewelry.py}.
 * <p>
 * A <b>named piece</b> (an artifact such as the Vampire Lich's Ring, Nov 13) is a definition
 * with some of these optional fields, from {@code tools/named_pieces.json}:
 * <ul>
 *     <li>{@code Name}: its English name for chat and logs (players see the item's
 *     translated name);</li>
 *     <li>{@code Spells}: spells it comes imbued with;</li>
 *     <li>{@code Cut}: its gem's cut ({@code GemCut} name), instead of Fine;</li>
 *     <li>{@code SpellOverrides}: its own cost, cooldown, effect or duration for its spells
 *     ({@link SpellOverrides});</li>
 *     <li>{@code Unlimited}: it spends no charge, so it needs no recharges;</li>
 *     <li>{@code Unbreakable}: casting spends no uses, so it needs no repairs;</li>
 *     <li>{@code Curses}: the price of its power, for example {@code Vanishing} (it is
 *     destroyed when its holder dies).</li>
 * </ul>
 *
 * @author Mark Gottschling on 11/09/2026
 */
public class JewelryDefinition implements JsonAssetWithMap<String, DefaultAssetMap<String, JewelryDefinition>> {
    public static final AssetBuilderCodec<String, JewelryDefinition> CODEC = AssetBuilderCodec.builder(
                    JewelryDefinition.class, JewelryDefinition::new, Codec.STRING,
                    (a, id) -> a.id = id, a -> a.id, (a, data) -> a.data = data, a -> a.data)
            .append(new KeyedCodec<>("Type", Codec.STRING, true), (a, v) -> a.type = v, a -> a.type).add()
            .append(new KeyedCodec<>("Material", Codec.STRING, true), (a, v) -> a.material = v, a -> a.material).add()
            .append(new KeyedCodec<>("Style", Codec.STRING), (a, v) -> a.style = v, a -> a.style).add()
            .append(new KeyedCodec<>("Gem", Codec.STRING), (a, v) -> a.gem = v, a -> a.gem).add()
            .append(new KeyedCodec<>("Name", Codec.STRING), (a, v) -> a.name = v, a -> a.name).add()
            .append(new KeyedCodec<>("Spells", Codec.STRING_ARRAY), (a, v) -> a.spells = v, a -> a.spells).add()
            .append(new KeyedCodec<>("Cut", Codec.STRING), (a, v) -> a.cut = v, a -> a.cut).add()
            .append(new KeyedCodec<>("SpellOverrides", SpellOverrides.CODEC), (a, v) -> a.spellOverrides = v,
                    a -> a.spellOverrides).add()
            .append(new KeyedCodec<>("Unlimited", Codec.BOOLEAN), (a, v) -> a.unlimited = v, a -> a.unlimited).add()
            .append(new KeyedCodec<>("Unbreakable", Codec.BOOLEAN), (a, v) -> a.unbreakable = v, a -> a.unbreakable).add()
            .append(new KeyedCodec<>("Curses", Codec.STRING_ARRAY), (a, v) -> a.curses = v, a -> a.curses).add()
            .build();

    private static AssetStore<String, JewelryDefinition, DefaultAssetMap<String, JewelryDefinition>> assetStore;

    protected AssetExtraInfo.Data data;
    protected String id;
    protected String type = "Ring";
    protected String material;
    protected String style = "Regular";
    protected String gem;
    protected String name;
    protected String[] spells;
    protected String cut;
    protected SpellOverrides spellOverrides;
    protected Boolean unlimited;
    protected Boolean unbreakable;
    protected String[] curses;

    /** The curse that destroys a piece when its holder dies. */
    public static final String CURSE_VANISHING = "Vanishing";
    private static final String[] NONE = new String[0];

    protected JewelryDefinition() {
    }

    public static AssetStore<String, JewelryDefinition, DefaultAssetMap<String, JewelryDefinition>> getAssetStore() {
        if (assetStore == null) {
            assetStore = AssetRegistry.getAssetStore(JewelryDefinition.class);
        }
        return assetStore;
    }

    public static DefaultAssetMap<String, JewelryDefinition> getAssetMap() {
        return getAssetStore().getAssetMap();
    }

    /**
     * @return the asset with this id, or null if there is none
     */
    @Nullable
    public static JewelryDefinition get(@Nullable String id) {
        return id == null ? null : getAssetMap().getAsset(id);
    }

    @Override
    public String getId() {
        return id;
    }

    public String getType() {
        return type;
    }

    @Nullable
    public String getMaterial() {
        return material;
    }

    public String getStyle() {
        return style;
    }

    @Nullable
    public String getGem() {
        return gem;
    }


    /**
     * @return a named piece's English name, for chat and logs, or null
     */
    @Nullable
    public String getName() {
        return name;
    }

    /**
     * @return the spells a new piece comes imbued with (a named piece's), usually none
     */
    public String[] getSpells() {
        return spells == null ? NONE : spells;
    }

    /**
     * @return a named piece's gem cut ({@code GemCut} name), or null for the usual Fine
     */
    @Nullable
    public String getCut() {
        return cut;
    }

    /**
     * @return a named piece's own spell numbers, or null if it uses the spells' own
     */
    @Nullable
    public SpellOverrides getSpellOverrides() {
        return spellOverrides;
    }

    /**
     * @return true if the piece spends no charge
     */
    public boolean isUnlimited() {
        return unlimited != null && unlimited;
    }

    /**
     * @return true if casting spends none of the piece's uses
     */
    public boolean isUnbreakable() {
        return unbreakable != null && unbreakable;
    }

    public String[] getCurses() {
        return curses == null ? NONE : curses;
    }

    public boolean hasCurse(String curse) {
        for (String c : getCurses()) {
            if (c.equalsIgnoreCase(curse)) {
                return true;
            }
        }
        return false;
    }

    /**
     * @return true for a named piece: one with any of the named fields
     */
    public boolean isNamed() {
        return name != null || getSpells().length > 0 || cut != null || spellOverrides != null || isUnlimited()
                || isUnbreakable() || getCurses().length > 0;
    }

    @Override
    public String toString() {
        return "JewelryDefinition{" + id + "}";
    }
}
