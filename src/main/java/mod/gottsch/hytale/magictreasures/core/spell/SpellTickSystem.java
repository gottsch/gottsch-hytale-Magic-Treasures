package mod.gottsch.hytale.magictreasures.core.spell;

import com.hypixel.hytale.component.ArchetypeChunk;
import com.hypixel.hytale.component.CommandBuffer;
import com.hypixel.hytale.component.Ref;
import com.hypixel.hytale.component.Store;
import com.hypixel.hytale.component.query.Query;
import com.hypixel.hytale.component.system.tick.DelayedEntitySystem;
import com.hypixel.hytale.server.core.entity.entities.Player;
import com.hypixel.hytale.server.core.universe.world.storage.EntityStore;

import javax.annotation.Nonnull;

/**
 * Once a second, runs each player's tick spells ({@link SpellEngine#tick}). The work is
 * queued to the world thread to run after the systems, because a cast can rewrite the
 * Jewelry Case in the player's inventory.
 *
 * @author Mark Gottschling on 11/09/2026
 */
public class SpellTickSystem extends DelayedEntitySystem<EntityStore> {
    public static final float INTERVAL_SECONDS = 1.0f;

    public SpellTickSystem() {
        super(INTERVAL_SECONDS);
    }

    @Nonnull
    @Override
    public Query<EntityStore> getQuery() {
        return Player.getComponentType();
    }

    @Override
    public void tick(float dt, int index, @Nonnull ArchetypeChunk<EntityStore> chunk, @Nonnull Store<EntityStore> store,
                     @Nonnull CommandBuffer<EntityStore> commandBuffer) {
        Ref<EntityStore> ref = chunk.getReferenceTo(index);
        store.getExternalData().getWorld().execute(() -> {
            if (ref.isValid()) {
                SpellEngine.tick(ref, store);
            }
        });
    }
}
